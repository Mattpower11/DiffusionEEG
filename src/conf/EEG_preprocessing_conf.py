from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path
from typing import Literal, Optional, Tuple


@dataclass(frozen=True)
class BCI2bSessionSpec:
    """One BCI Competition IV 2b session.

    Epoch offsets are seconds relative to the onset of the cue event, not
    relative to the start-of-trial event 768.
    """

    subject_id: int
    session_id: str
    split: Literal["train", "test"]
    protocol: Literal["screening", "feedback"]
    cue_annotations: Tuple[str, ...]
    tmin: float
    tmax: float
    labels_source: Literal["gdf", "external_mat"]


@dataclass
class EEG_preprocessing_conf:
    """Shared BCI2b preprocessing settings, compatible with existing callers.

    The legacy tmin/tmax are the screening-window settings. New epoch code
    should call session_spec(filename) for per-session events and timing.
    A configuration object describes labels but does not load .mat files.
    """

    # Automatic diagnostics
    report_output_dir: str = "./report/processing"

    sfreq_expected: float = 250.0
    sfreq_tolerance: float = 0.01
    eeg_channel_names: Tuple[str, ...] = ("C3", "Cz", "C4")
    eog_channel_pattern: str = r"(?i)\bEOG\b|EOG"

    # Continuous-data gaps and run boundaries
    gap_guard_seconds: float = 0.5
    expected_run_gap_samples: int = 100
    sentinel_atol_volts: float = 1e-9

    # Filters (Hz)
    l_freq: float = 0.5
    h_freq: float = 40.0
    notch_freq: Optional[float] = None

    # Screening (01T/02T): two seconds after the 1.25-s visual cue,
    # relative to 769/770. These are unchanged legacy settings.
    tmin: float = 1.25
    tmax: float = 3.244

    # Feedback sessions (03T/04E/05E): official paradigm shows cue at
    # trial second 3, continuous feedback at trial second 4. Hence the
    # feedback period starts approximately 1.0 s after the cue. The 2-s
    # excerpt is an experimental choice, not an official required duration.
    # Both offsets below are relative to cue (769/770/783), NOT to event 781.
    feedback_tmin: float = 1.0
    feedback_tmax: float = 2.996

    # Exact GDF annotation descriptions, not integers generated by MNE.
    screening_train_cues: Tuple[str, ...] = ("769", "770")
    feedback_train_cues: Tuple[str, ...] = ("769", "770")
    feedback_test_cues: Tuple[str, ...] = ("783",)
    trial_start_annotation: str = "768"
    rejected_trial_annotation: str = "1023"
    feedback_onset_annotation: str = "781"
    run_start_annotation: str = "32766"

    # True labels (original values 1=left and 2=right) may be provided
    # from true_labels.zip or extracted Bxx0yE.mat files. Only evaluation
    # sessions need the external labels; the .mat files of training sessions
    # may also be used for independent consistency checks.
    labels_archive_path: Optional[str] = None
    labels_variable_name: str = "classlabel"
    matlab_left_hand_label: int = 1
    matlab_right_hand_label: int = 2
    output_left_hand_label: int = 0
    output_right_hand_label: int = 1
    require_external_evaluation_labels: bool = True

    # 500 samples = 2 seconds at 250 Hz. No resampling by default.
    sequence_length: Optional[int] = 500
    resample_sfreq: Optional[float] = None
    overlap: float = 0.0
    enforce_epoch_length: bool = True

    # Artifact controls (preserved from the supplied configuration)
    artifact_mode: str = "basic"
    peak_to_peak_threshold_uv: float = 200.0
    flat_threshold_uv: float = 0.5
    ica_eog_threshold: float = 0.7
    ica_auto_remove: bool = False
    ica_max_components_to_remove: int = 1
    ica_strict: bool = True

    # Fit train statistics only; reuse those statistics for test.
    normalization: str = "train"
    eps: float = 1e-6
    random_seed: int = 42

    def session_spec(self, gdf_file: str | Path) -> BCI2bSessionSpec:
        """Resolve session parameters by strict official filename.

        B0101T and B0102T: screening/training, cue 769 or 770.
        B0103T: feedback/training, cue 769 or 770.
        B0104E and B0105E: feedback/test, unknown cue 783.
        """
        filename = Path(gdf_file).name
        match = re.fullmatch(
            r"B(?P<subject>0[1-9])(?P<session>0[1-5])(?P<kind>[TE])\.gdf",
            filename,
            flags=re.IGNORECASE,
        )

        if match is None:
            raise ValueError(f"Unrecognized BCI IV 2b GDF filename: {filename!r}")

        subject = int(match.group("subject"))
        session = int(match.group("session"))
        kind = match.group("kind").upper()
        expected_kind = "T" if session <= 3 else "E"
        
        if kind != expected_kind:
            raise ValueError(
                f"Session {session:02d} requires suffix {expected_kind}, "
                f"but got {kind} in {filename!r}"
            )
        
        session_id = f"{session:02d}{kind}"
        
        if session <= 2:
            return BCI2bSessionSpec(
                subject, session_id, "train", "screening",
                self.screening_train_cues, self.tmin, self.tmax, "gdf",
            )
        
        if session == 3:
            return BCI2bSessionSpec(
                subject, session_id, "train", "feedback",
                self.feedback_train_cues, self.feedback_tmin,
                self.feedback_tmax, "gdf",
            )
        
        return BCI2bSessionSpec(
            subject, session_id, "test", "feedback",
            self.feedback_test_cues, self.feedback_tmin,
            self.feedback_tmax, "external_mat",
        )

    def expected_epoch_samples(self, tmin: float, tmax: float) -> int:
        """Return MNE Epochs sample count, with inclusive endpoints."""
        # resampling is deliberately unsupported by this configuration.
        sfreq = self.sfreq_expected
        return int(round(tmax * sfreq) - round(tmin * sfreq) + 1)

    def validate(self) -> None:
      """Fail early for inconsistent or unsupported parameter combinations."""
      if self.sfreq_expected <= 0 or self.sfreq_tolerance < 0:
        raise ValueError("Sampling frequency must be positive; tolerance cannot be negative")
      
      if not (0 <= self.l_freq < self.h_freq < self.sfreq_expected / 2):
        raise ValueError("Invalid EEG filtering band")
      
      if self.notch_freq is not None and not (0 < self.notch_freq < self.sfreq_expected / 2):
        raise ValueError("Notch frequency must be within (0, Nyquist)")
      
      if len(self.eeg_channel_names) != 3 or len(set(self.eeg_channel_names)) != 3:
          raise ValueError("Exactly three distinct EEG channel names are required")
      
      if not all(isinstance(x, str) and x.strip() for x in self.eeg_channel_names):
          raise ValueError("EEG channel names cannot be empty")
      
      try:
          re.compile(self.eog_channel_pattern)
      except re.error as exc:
          raise ValueError("Invalid eog_channel_pattern") from exc

      if self.gap_guard_seconds < 0 or self.expected_run_gap_samples <= 0:
          raise ValueError("Gap guard must be nonnegative; gap sample count must be positive")
      
      if self.sentinel_atol_volts < 0:
          raise ValueError("sentinel_atol_volts must be nonnegative")

      for name, cues in (
          ("screening_train_cues", self.screening_train_cues),
          ("feedback_train_cues", self.feedback_train_cues),
          ("feedback_test_cues", self.feedback_test_cues),
      ):
        if not cues or len(set(cues)) != len(cues) or not all(
          isinstance(v, str) and v.strip() for v in cues
        ):
          raise ValueError(f"{name} must contain nonempty, unique descriptions")
      
      if len(self.screening_train_cues) != 2 or len(self.feedback_train_cues) != 2:
        raise ValueError("Training sessions require two distinct cue descriptions")
      
      if len(self.feedback_test_cues) != 1:
        raise ValueError("Evaluation sessions require one unknown-cue description")
      
      for name in (
        "trial_start_annotation", "rejected_trial_annotation",
        "feedback_onset_annotation", "run_start_annotation",
        "labels_variable_name",
      ):
        value = getattr(self, name)
          
        if not isinstance(value, str) or not value.strip():
          raise ValueError(f"{name} must be a nonempty string")

      if self.matlab_left_hand_label == self.matlab_right_hand_label:
        raise ValueError("The two MATLAB class values must differ")
      
      if (self.output_left_hand_label, self.output_right_hand_label) != (0, 1):
        raise ValueError("BioDiffusion labels must be 0=left, 1=right")
      
      if self.labels_archive_path is not None:
        path = Path(self.labels_archive_path)
          
        if not path.exists() or not (path.is_file() or path.is_dir()):
          raise ValueError(f"labels_archive_path does not exist: {path}")
      
      if self.resample_sfreq is not None:
        raise ValueError("Resampling is unsupported in this preprocessing configuration")
      
      if self.overlap != 0:
        raise ValueError("Overlapping windows are not implemented")
      
      if self.normalization != "train":
        raise ValueError("Use train-only normalization to avoid test leakage")
      
      if self.eps <= 0:
        raise ValueError("Normalization epsilon must be positive")
      
      if self.artifact_mode not in ("basic", "ica"):
        raise ValueError("artifact_mode must be 'basic' or 'ica'")
      
      if self.peak_to_peak_threshold_uv <= 0 or self.flat_threshold_uv < 0:
        raise ValueError("Artifact amplitude/flat thresholds are invalid")
      
      if not 0 <= self.ica_eog_threshold <= 1:
        raise ValueError("ica_eog_threshold must be in [0,1]")
      
      if self.ica_max_components_to_remove < 0 or self.ica_max_components_to_remove > 3:
        raise ValueError("ICA removal count must be between zero and three")

      if not (0 <= self.tmin < self.tmax and 0 <= self.feedback_tmin < self.feedback_tmax):
        raise ValueError("Epoch intervals must have 0 <= tmin < tmax")
      
      # Official schematic: cue at 3 s; keep windows inside each
      # task period. Trial and pause durations can vary.
      if 3.0 + self.tmax > 8.0:
        raise ValueError("Screening epoch exceeds the 8-second trial")
      
      if 3.0 + self.feedback_tmax > 8.5:
        raise ValueError("Feedback epoch exceeds the 8.5-second trial")
      
      if self.sequence_length is not None:
        if self.sequence_length <= 0:
          raise ValueError("sequence_length must be positive when specified")
        
        if self.enforce_epoch_length:
          for name, lo, hi in (
            ("screening", self.tmin, self.tmax),
            ("feedback", self.feedback_tmin, self.feedback_tmax),
          ):
            n = self.expected_epoch_samples(lo, hi)
            if n != self.sequence_length:
              raise ValueError(
                f"{name} epoch produces {n} samples at "
                f"{self.sfreq_expected:g} Hz; expected {self.sequence_length}"
              )
  